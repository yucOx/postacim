export function serverMsg(msg: string): string {
  const locale = useI18nStore.getState().locale;
  if (locale === 'tr') return msg; // tablo anahtarları Türkçe — çeviri gereksiz
  const row = TABLE[msg] as Partial<Record<string, string>> | undefined;
  return row?.[locale] ?? msg;
}
